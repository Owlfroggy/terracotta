function recurse(e: Expression): string {
    if (e instanceof NumberExpression) {
        return e.token.value;
    } else if (e instanceof BinaryExpression) {
        return `(${recurse(e.left)} ${e.operator.value} ${recurse(e.right)})`
    }
    return "";
}

